#!/usr/bin/env bash
# Regenerates docs/diff_vs_orchard_circuit.md: `diff -u` of Config::configure and synthesize_base,
# orchard 0.15.3 (from the cargo registry) against src/circuit.rs. Run from the repository root.
set -euo pipefail
O=$(ls "${CARGO_HOME:-$HOME/.cargo}"/registry/src/*/orchard-0.15.3/src/circuit.rs | head -1)
T=$(mktemp -d); trap 'rm -rf "$T"' EXIT
x() { python3 -I tools/circuit_diff_extract.py "$1" "$2" "$3"; }
CONF='fn configure\(meta: &mut plonk::ConstraintSystem<pallas::Base>\) -> Self \{'
oc=$(x "$O" "$CONF" "$T/oc"); wc_=$(x src/circuit.rs "$CONF" "$T/wc")
os=$(x "$O" 'fn synthesize_base\(' "$T/os"); ws=$(x src/circuit.rs 'fn synthesize_base\(' "$T/ws")
r() { echo "${1##*:}"; }
{
cat <<HEAD
# Wake circuit vs orchard 0.15.3 src/circuit.rs

Regenerated by \`tools/regenerate_circuit_diff.sh\` (first written 2026-09-25 by hand; regenerated
2026-10-08 after an automated review found the hand copy showed the sabotage guards as
\`self.skips(sab(SabName::X))\` where the code reads \`self.skips(SabName::X)\`; finding WAKE F-13).
\`diff -u\` of each function, extracted by brace matching. Left: orchard. Right: \`src/circuit.rs\`.
Expected content: deletions, the unconditional \`root = anchor\`, \`pk_d_old\` witnessed, and the one added \`LINK\` constraint.
The \`if !self.skips(SabName::…)\` guards are the chapter 5 sabotage knob; they are \`false\` in every build
without the test-only \`sabotage\` feature (see the pinned vk_id test).

## Config::configure  (orchard lines $(r "$oc"), wake lines $(r "$wc_"))

\`\`\`diff
HEAD
diff -u --label orchard --label wake "$T/oc" "$T/wc" | tail -n +3 || true
printf '%s\n\n## synthesize_base  (orchard lines %s, wake lines %s)\n\n%s\n' '```' "$(r "$os")" "$(r "$ws")" '```diff'
diff -u --label orchard --label wake "$T/os" "$T/ws" | tail -n +3 || true
echo '```'
} > docs/diff_vs_orchard_circuit.md
echo "wrote docs/diff_vs_orchard_circuit.md"
